/** Small deterministic generator (mulberry32); `kaigenRand(seed, n)` gives the n-th draw independent of any simulation state. */
export function kaigenRand(seed: number, n: number): number {
  let t = ((seed ^ 0x9e3779b9) + Math.imul(n + 1, 0x85ebca6b)) >>> 0;
  t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}
export function futureInterval(seed: number, idx: number): number {
  const lo = FUTURE_INTERVAL.base - FUTURE_INTERVAL.spread, hi = FUTURE_INTERVAL.base + FUTURE_INTERVAL.spread;
  return lo + Math.floor(kaigenRand(seed, idx) * (hi - lo + 1));
}
/** The five candidate names for a kaigen in `year`, fewest strokes first. `taken` = names this game has already used. */
export function futureCandidates(year: number, taken: Set<string> = new Set()): EraCand[] {
  const e = eto(year), parts: [string, number, number][] = [[e.stem[0], e.stem[1], 0], [e.branch[0], e.branch[1], 1]], rows: { name: string; strokes: number; key: number }[] = [];
  IROHA.forEach((ir, i) => { for (const [c, st, kind] of parts) for (const order of [0, 1]) rows.push({ name: order === 0 ? ir.kanji + c : c + ir.kanji, strokes: ir.strokes + st, key: i * 8 + kind * 2 + order }); });
  const seen = new Set<string>(), out: EraCand[] = [];
  for (const r of rows.sort((a, b) => a.strokes - b.strokes || a.key - b.key)) {
    if (seen.has(r.name) || USED_NAMES.has(r.name) || taken.has(r.name) || FORBIDDEN_WORDS.has(r.name) || [...r.name].some((ch) => FORBIDDEN_CHARS.has(ch))) continue;
    seen.add(r.name); out.push({ name: r.name, stance: CYCLE[out.length % CYCLE.length], real: false, note: `暫定規則で生成(${r.strokes}画・${e.label}年)` });
    if (out.length >= FUTURE_CANDIDATES) break;
  }
  return out;
}

// ---------------------------------------------------------------- the timeline ----------
export const newKaigen = (first: EraCand, firstIdx: number, seed: number): KaigenState => ({ eras: [{ name: first.name, start: FIRST_YEAR, stance: first.stance, real: first.real, picked: firstIdx, of: CAND_1945.length, auto: false }], pending: null, next: KAIGEN_YEARS.second, nextIdx: 0, ...(first.recon ? { recon: { ...first.recon } } : {}) });
export function candidatesFor(k: KaigenState, year: number): EraCand[] {
  if (year === KAIGEN_YEARS.second) return CAND_1989; if (year === KAIGEN_YEARS.third) return CAND_2019;
  return futureCandidates(year, new Set(k.eras.map((x) => x.name)));
}
/** Is a kaigen due at the start of `year`? Opens it (pending) and returns true. Never opens twice for one year. */
export function kaigenDue(k: KaigenState | undefined, year: number): boolean { return !!k && !k.pending && year >= k.next; }
export function openKaigen(k: KaigenState, year: number): void { k.pending = { year, cands: candidatesFor(k, year) }; }
/** Choose candidate `idx` (the pending one). The next date is scheduled; returns the new entry. */
export function chooseEra(k: KaigenState, idx: number, seed: number, auto = false): EraEntry | null {
  const p = k.pending; if (!p) return null; const i = Math.max(0, Math.min(p.cands.length - 1, Math.floor(idx))), c = p.cands[i];
  const e: EraEntry = { name: c.name, start: p.year, stance: c.stance, real: c.real, picked: i, of: p.cands.length, auto };
  k.eras.push(e); k.pending = null;
  if (p.year < KAIGEN_YEARS.third) k.next = p.year === KAIGEN_YEARS.second ? KAIGEN_YEARS.third : KAIGEN_YEARS.second; else { k.next = p.year + futureInterval(seed, k.nextIdx); k.nextIdx++; }
  return e;
}
/** The era in force in `year` (null before the first), and its year number (元年 = 1). */
export function eraAt(eras: EraEntry[], year: number): { name: string; n: number } | null {
  let cur: EraEntry | null = null; for (const e of eras) if (e.start <= year) cur = e; if (!cur) return null; return { name: cur.name, n: year - cur.start + 1 };
}
export const eraText = (eras: EraEntry[], year: number): string => { const e = eraAt(eras, year); return e ? `${e.name}${e.n === 1 ? "元" : e.n}年` : `${year}年`; };

/**
 * How much each past choice still weighs in `year` (sums to 1). Stage 7: policy direction ACCUMULATES. Every era weighs by how long it was in force
 * (its years so far), and the era in force counts CURRENT_WEIGHT times, so a new era phases in by itself as its years add up (no separate ramp) and an
 * era that lasted 44 years still carries about a fifth of the direction in 2100. Before, every new era halved what came before (MEMORY = 0.5 per step),
 * so two era changes erased three quarters of the first choice whatever its length -- which is why the ten-yearly policy window could outweigh it.
 * Returns one weight per era, oldest first.
 */
export const CURRENT_WEIGHT = 2, RAMP_YEARS = 6, MEMORY = 0.5;   // RAMP_YEARS / MEMORY: kept for the documentation of the old rule only
export function eraWeights(eras: EraEntry[], year: number): number[] {
  const w = eras.map(() => 0); let cur = 0;
  for (let i = 0; i < eras.length; i++) if (eras[i].start <= year) cur = i;
  for (let i = 0; i <= cur; i++) { const end = i < cur ? eras[i + 1].start : year, d = Math.max(0, end - eras[i].start); w[i] = d * (i === cur ? CURRENT_WEIGHT : 1); }
  const sum = w.reduce((p, q) => p + q, 0); if (sum <= 0) { w.fill(0); w[cur] = 1; return w; }
  return w.map((x) => x / sum);
}

/** The stance (and so the dial profile) in force in `year`: the era entry in force for a timeline game, the one fixed era otherwise. */
export function stanceAt(sim: { era: string; kaigen?: KaigenState }, year: number): EraKey {
  if (sim.kaigen) { let cur: EraEntry | null = null; for (const e of sim.kaigen.eras) if (e.start <= year) cur = e; if (cur) return cur.stance; }
  return (["heisei", "shubun", "shoka", "kobun"].includes(sim.era) ? sim.era : "kobun") as EraKey;
}
