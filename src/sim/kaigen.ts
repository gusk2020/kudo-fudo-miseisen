/** 「ぬ」の字母は「奴」だが語感が不適切なため、中立な「縫」に置き換えている(暫定)。 */
export const REPLACED: Record<string, string> = { "ぬ": "縫" };
/** 干支: ten stems (十干) and twelve branches (十二支), with stroke counts. The year's own stem and branch are the two characters offered for combining. */
export const STEMS = [["甲", 5], ["乙", 1], ["丙", 5], ["丁", 2], ["戊", 5], ["己", 3], ["庚", 8], ["辛", 7], ["壬", 4], ["癸", 9]] as const;
export const BRANCHES = [["子", 3], ["丑", 4], ["寅", 11], ["卯", 5], ["辰", 7], ["巳", 3], ["午", 4], ["未", 5], ["申", 5], ["酉", 7], ["戌", 6], ["亥", 6]] as const;
/** The sexagenary pair of a year (1984 = 甲子). */
export function eto(year: number): { stem: [string, number]; branch: [string, number]; label: string } {
  const s = STEMS[(((year - 4) % 10) + 10) % 10], b = BRANCHES[(((year - 4) % 12) + 12) % 12];
  return { stem: [s[0], s[1]], branch: [b[0], b[1]], label: s[0] + b[0] };
}
/** Characters and words that may not appear in a future era name (ill-omened or too grim). A name containing any of these is dropped before ranking. */
export const FORBIDDEN_CHARS = new Set(["奴", "死", "亡", "凶", "乱", "戦", "病", "災", "滅", "悪", "害"]);
export const FORBIDDEN_WORDS = new Set(["丑己", "己丑", "乙己"]);   // reserved for words found awkward on review; extend freely
