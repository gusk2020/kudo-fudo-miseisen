/**
 * 改元 (era changes) and the 世界線方針 each choice sets (Issue #13).
 *
 * Timeline of a new game:
 *   1945  昭和 ends (this world's history).      First era chosen from the REAL candidates that were passed over when 昭和 was named (1926).
 *   1989  the era chosen for 平成 in reality.    Choose among 平成 and its two real alternates.
 *   2019  the era of 令和 in reality.            Choose among 令和 and its four real alternates.
 *   after 2019: every 30 ± 3 years (27..33, deterministic from the game seed) -- a PROVISIONAL rule, see FUTURE_RULES.
 *
 * What is real and what is not (kept explicit, as everywhere in this project):
 *  - Candidate NAMES for 1926 / 1989 / 2019 are historical (sources below); that they were candidates is real, that they were chosen here is the game's.
 *  - Which candidate leans toward roads or rails (`stance`) is NOT historical. It is a fixed, arbitrary table (cycling balanced / road / rail in the
 *    order the sources list the candidates) so the player can see what each choice does; it says nothing about the real candidates' meaning.
 *  - Future candidate names are generated by FUTURE_RULES, a prototype. Every rule that is a judgement call is a named constant here so it can be changed.
 *
 * Sources for the real candidates (checked 2026-10-15 by web search; the primary documents themselves were not reachable from this environment):
 *  - 昭和 (1926): 宮内省案 十件「昭和・神化・元化・神和・同和・継明・順明・明保・寛安・元安」(倉富勇三郎日記), 内閣案 五件「立成・定業・光文・章明・協中」 -- via
 *    zatsuneta.com/archives/112252.html, bestcalendar.jp/dates/kinenbi/5130, gendai.media/articles/-/149237 and /-/152092. 「昭和」 itself is the one this world
 *    did NOT keep, so it is not offered. 「光文」 is the candidate a newspaper wrongly reported as chosen (光文事件).
 *  - 平成 (1989): 「平成・修文・正化」 (three candidates; proposers were not published) -- dic.nicovideo.jp/t/a/平成, xinmin.cn 2019-04-01.
 *  - 令和 (2019): 「令和・英弘・久化・広至・万保」 (one English-language source prints 万和 beside 万保, which looks like a slip) -- news.livedoor.com/article/detail/17083568,
 *    kanpai-japan.com. 「天翔」 was reported as a front-runner but was not one of the five put to the Cabinet.
 */
import type { EraKey } from "./eras";

export interface EraCand { name: string; stance: EraKey; real: boolean; note: string; recon?: Recon }
/** Stage 10: the 1945 reconstruction policy (recon.ts). Only the first era choice carries one. */
export interface Recon { coast: "pacific" | "japansea"; focus: "concentrate" | "disperse" }
export interface EraEntry { name: string; start: number; stance: EraKey; real: boolean; picked: number; of: number; auto: boolean }
export interface KaigenState { eras: EraEntry[]; pending: { year: number; cands: EraCand[] } | null; next: number; nextIdx: number; recon?: Recon }

/** The policy stances a candidate can carry, in the order they are handed out. Issue #15 added 空路重視 and 海路重視 to the original three. */
export const STANCES: EraKey[] = ["heisei", "shubun", "shoka", "kuuro", "kairo"];
const CYCLE = STANCES;
/** Stage 19: the groups of the era lists, by transport stance. A candidate's stance IS its main policy effect (eras.ts: 道路重視 = roads and cars first, 鉄道重視 = railways and public transport, 海路重視 = ports and ferries,
 *  空路重視 = airports, 均衡 = roads and railways side by side), so each stance is its own group; a group with no candidate is not shown. */
export type EraGroup = "road" | "rail" | "sea" | "air" | "balanced";
export const ERA_GROUPS: EraGroup[] = ["road", "rail", "sea", "air", "balanced"];
export const ERA_GROUP_LABEL: Record<EraGroup, string> = { road: "道路系", rail: "鉄道系", sea: "海路系", air: "空路系", balanced: "均衡系" };
export function eraGroup(stance: EraKey): EraGroup { return stance === "shubun" ? "road" : stance === "shoka" ? "rail" : stance === "kairo" ? "sea" : stance === "kuuro" ? "air" : "balanced"; }
export const STANCE_LABEL: Record<EraKey, string> = { heisei: "均衡", shubun: "道路重視", shoka: "鉄道重視", kuuro: "空路重視", kairo: "海路重視", kobun: "旧版" };
/**
 * ERA -> STANCE TABLE (the one place that says which candidate leans which way). PROVISIONAL, and not historical: the real candidates keep their real names, and the
 * lean is handed out by position in the list the sources give, cycling 均衡 -> 道路 -> 鉄道 -> 空路 -> 海路. 1989 has only three real candidates, so it keeps the three it has always had
 * (no air / sea candidate exists there; the real names are not stretched to fill a gap). `eraTable()` prints it for the docs and a test pins it.
 */
const cyc = (names: string[], note: (n: string) => string): EraCand[] => names.map((name, i) => ({ name, stance: CYCLE[i % CYCLE.length], real: true, note: note(name) }));

/** Stage 10: the reconstruction policy, the four combinations in turn (independent of the stance cycle of five, so every combination meets several stances). */
const withRecon = (l: EraCand[]): EraCand[] => l.map((c, i) => ({ ...c, recon: { coast: i % 2 === 0 ? "pacific" : "japansea", focus: Math.floor(i / 2) % 2 === 0 ? "concentrate" : "disperse" } }));
/** 1945: the candidates passed over in 1926 (昭和 itself excluded). Order: 宮内省案, then 内閣案. */
export const CAND_1945: EraCand[] = withRecon(cyc(["神化", "元化", "神和", "同和", "継明", "順明", "明保", "寛安", "元安", "立成", "定業", "光文", "章明", "協中"], (n) => `1926年の${["神化", "元化", "神和", "同和", "継明", "順明", "明保", "寛安", "元安"].includes(n) ? "宮内省案" : "内閣案"}`));
/** 1989: 平成 is the real choice and comes first. These three keep the stances the game has always used for them. */
export const CAND_1989: EraCand[] = [
  { name: "平成", stance: "heisei", real: true, note: "1989年の実際の新元号" }, { name: "修文", stance: "shubun", real: true, note: "1989年の候補(落選)" }, { name: "正化", stance: "shoka", real: true, note: "1989年の候補(落選)" }];
export const CAND_2019: EraCand[] = cyc(["令和", "英弘", "久化", "広至", "万保"], (n) => (n === "令和" ? "2019年の実際の新元号" : "2019年の候補(落選)"));
export const eraTable = () => [["1945(1926年の落選案)", CAND_1945], ["1989", CAND_1989], ["2019", CAND_2019]].map(([y, l]) => `${y}: ` + (l as EraCand[]).map((c) => `${c.name}=${STANCE_LABEL[c.stance]}`).join(" / ")).join("\n");
export const FIRST_YEAR = 1945, KAIGEN_YEARS = { second: 1989, third: 2019 } as const;

